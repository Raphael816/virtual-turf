export type RunningStyle = 'nige' | 'senko' | 'sashi' | 'oikomi';
export type Grade = 'A' | 'B' | 'C' | 'D';

export interface Horse {
  id: string;
  name: string;
  sex: '牡' | '牝' | 'セ';
  age: number;
  color: string; // 毛色（3D表示用）
  coat: string; // 毛色名
  trainer: string;
  /** 能力値 0-100 */
  speed: number;
  stamina: number;
  accel: number;
  /** ゲートの上手さ */
  start: number;
  /** 気性の安定度（高いほど落ち着いている） */
  temper: number;
  /** パワー（重い馬場・ダートで効く） */
  power: number;
  style: RunningStyle;
  /** 最適距離 (m) */
  bestDistance: number;
  turf: Grade;
  dirt: Grade;
  /** 道悪（重・不良）適性 */
  heavy: Grade;
  note: string;
}

